import matplotlib.pyplot as plt
import matplotlib.animation as animation
from IPython.display import HTML
import numpy as np

# ===== Aqui configuramos el tablero =====
n = 10
board = np.zeros((n, n))
x, y = 0, 0  # Aqui inicia el robot
trayectoria = [(x, y)]
board[x, y] = 1

# ===== MOVIMIENTO SIMULADO =====
# CORRECCIÓN: antes los datos no eran una secuencia válida (x, y sueltos)
for i in range(1, n):
    trayectoria.append((x, i))
for i in range(1, n):
    trayectoria.append((i, n-1))
for i in range(n-2, -1, -1):
    trayectoria.append((n-1, i))
for i in range(n-2, 0, -1):
    trayectoria.append((i, 0))

# ===== FUNCIÓN DE ANIMACIÓN =====
fig, ax = plt.subplots(figsize=(5, 5))
ax.set_xticks(range(n))
ax.set_yticks(range(n))
ax.set_xlim(-0.5, n-0.5)
ax.set_ylim(-0.5, n-0.5)
ax.grid(True)
ax.set_title("Simulación robot aspiradora")

robot_point, = ax.plot([], [], 'ro', markersize=12)  # CORRECCIÓN: debe ser una secuencia (listas)
path_line, = ax.plot([], [], 'b-', lw=1)

def init():
    robot_point.set_data([], [])
    path_line.set_data([], [])
    return robot_point, path_line

def update(frame):
    x_vals = [p[1] for p in trayectoria[:frame+1]]
    y_vals = [p[0] for p in trayectoria[:frame+1]]
    robot_point.set_data(x_vals[-1:], y_vals[-1:])  # CORRECCIÓN: usar listas, no números sueltos
    path_line.set_data(x_vals, y_vals)
    return robot_point, path_line

ani = animation.FuncAnimation(fig, update, frames=len(trayectoria),
                              init_func=init, blit=True, interval=300)

plt.close(fig)

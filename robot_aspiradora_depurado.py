# CORRECCIÓN: Antes el código usaba variables globales definidas con input().

GRID_W = 15
GRID_H = 10
NUM_DIRT = 25
STEPS = 400

random.seed(42)
np.random.seed(42)

class Board:
    def __init__(self, width, height, num_dirt):
        self.width = width
        self.height = height

        self.grid = np.zeros((height, width), dtype=int)

        for _ in range(num_dirt):
            x = random.randrange(width)
            y = random.randrange(height)
            self.grid[y, x] = 1

    def is_dirty(self, x, y):
        return self.grid[y, x] == 1

    def clean(self, x, y):
        self.grid[y, x] = 0

    def dirt_count(self):
        return int(self.grid.sum())


class Robot:
    def __init__(self, board, x=0, y=0):
        self.board = board

        self.x = max(0, min(board.width - 1, x))
        self.y = max(0, min(board.height - 1, y))
        self.cleaned = 0

    def step(self):

        if self.board.is_dirty(self.x, self.y):
            self.board.clean(self.x, self.y)
            self.cleaned += 1
            return

        moves = [(0,1),(0,-1),(1,0),(-1,0)]
        dx, dy = random.choice(moves)
        nx = self.x + dx
        ny = self.y + dy
        if 0 <= nx < self.board.width and 0 <= ny < self.board.height:
            self.x = nx
            self.y = ny


# CORRECCIÓN: encapsulé creación del tablero y robot en una función para facilitar ejecución repetida.
def make_sim(width=GRID_W, height=GRID_H, num_dirt=NUM_DIRT):
    board = Board(width, height, num_dirt)
    # esto inicia el robot en el centro del tablero
    robot = Robot(board, x=width//2, y=height//2)
    return board, robot

